CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. Global Site & SEO Settings (Favicon, Default 1200x630 OG Image, Robots.txt, Domain)
CREATE TABLE IF NOT EXISTS public.site_settings (
  id TEXT PRIMARY KEY DEFAULT 'global',
  site_name TEXT NOT NULL DEFAULT 'AarviCloud IT Solutions',
  site_domain TEXT NOT NULL DEFAULT 'https://aarvicloud.com',
  default_meta_title TEXT NOT NULL DEFAULT 'AarviCloud | Enterprise AI, Cloud Solutions & Custom Software Development Company',
  default_meta_description TEXT NOT NULL DEFAULT 'AarviCloud engineers production-grade Generative AI, secure cloud architectures, ERP/CRM systems, and custom web & mobile apps for global enterprises.',
  default_keywords TEXT NOT NULL DEFAULT 'AI Development Company, Cloud Solutions, Custom Software Development, ERP Development Rajkot, Cyber Security Consulting, React Node.js Development, AarviCloud',
  default_meta_robots TEXT NOT NULL DEFAULT 'index, follow',
  favicon_url TEXT NOT NULL DEFAULT '/logo.png',
  default_og_image TEXT NOT NULL DEFAULT '/api/og-default.svg',
  og_image_width INTEGER NOT NULL DEFAULT 1200,
  og_image_height INTEGER NOT NULL DEFAULT 630,
  robots_txt TEXT NOT NULL DEFAULT E'User-agent: *\nAllow: /\nDisallow: /admin\nDisallow: /api/\n\nSitemap: https://aarvicloud.com/sitemap.xml',
  google_site_verification TEXT DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Per-Page SEO Configuration (Meta Title, Description, Keywords, Meta Robots, OG Tags, H1-H6 Config)
CREATE TABLE IF NOT EXISTS public.page_seo (
  page_key TEXT PRIMARY KEY, -- e.g. 'home', 'about', 'portfolio', 'case-studies', 'blog', 'contact', 'privacy-policy', 'terms-of-service'
  route_path TEXT NOT NULL,  -- e.g. '/', '/about', '/portfolio', etc.
  meta_title TEXT NOT NULL,
  meta_description TEXT NOT NULL,
  target_keywords TEXT NOT NULL DEFAULT '',
  meta_robots TEXT NOT NULL DEFAULT 'index, follow',
  og_title TEXT NOT NULL DEFAULT '',
  og_description TEXT NOT NULL DEFAULT '',
  og_image TEXT NOT NULL DEFAULT '',
  og_url TEXT NOT NULL DEFAULT '',
  canonical_url TEXT NOT NULL DEFAULT '',
  h1_heading TEXT NOT NULL DEFAULT '',
  priority NUMERIC(2,1) NOT NULL DEFAULT 0.8,
  changefreq TEXT NOT NULL DEFAULT 'weekly',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Dynamic Page Content Sections (Home, About, Contact, Footer, CaseStudies Header, Privacy, Terms)
CREATE TABLE IF NOT EXISTS public.page_sections (
  section_key TEXT PRIMARY KEY, -- 'home', 'about', 'contact', 'footer', 'case_studies_page', 'privacy_policy', 'terms_of_service'
  content JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Dynamic Blog Posts (Auto Sitemap + Full SEO + H1-H6 Hierarchy)
CREATE TABLE IF NOT EXISTS public.blogs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  excerpt TEXT NOT NULL,
  content TEXT NOT NULL,
  image TEXT NOT NULL,
  author TEXT NOT NULL DEFAULT 'AarviCloud Team',
  date TEXT NOT NULL,
  read_time TEXT NOT NULL DEFAULT '8 min read',
  category TEXT NOT NULL DEFAULT 'Cloud',
  tags TEXT[] NOT NULL DEFAULT ARRAY['Cloud', 'AI', 'Technology'],
  published BOOLEAN NOT NULL DEFAULT TRUE,
  meta_title TEXT NOT NULL DEFAULT '',
  meta_description TEXT NOT NULL DEFAULT '',
  target_keywords TEXT NOT NULL DEFAULT '',
  meta_robots TEXT NOT NULL DEFAULT 'index, follow',
  og_title TEXT NOT NULL DEFAULT '',
  og_description TEXT NOT NULL DEFAULT '',
  og_image TEXT NOT NULL DEFAULT '',
  og_url TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Dynamic Portfolio Projects
CREATE TABLE IF NOT EXISTS public.portfolio_projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE,
  title TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'Development',
  image TEXT NOT NULL,
  description TEXT NOT NULL,
  tech TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  url TEXT DEFAULT '',
  featured_on_home BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  published BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. Dynamic Case Studies (Auto Sitemap + Full Detail + Full SEO)
CREATE TABLE IF NOT EXISTS public.case_studies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  section_category TEXT NOT NULL DEFAULT 'Fortune 500 Clients',
  badge_category TEXT NOT NULL DEFAULT 'Enterprise',
  image TEXT NOT NULL,
  is_new BOOLEAN NOT NULL DEFAULT TRUE,
  challenge TEXT NOT NULL,
  solution TEXT NOT NULL,
  results TEXT NOT NULL,
  tech TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  features TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  stats JSONB NOT NULL DEFAULT '[{"label":"60% Faster Performance","icon":"BarChart"},{"label":"1M+ Active Users","icon":"Users"},{"label":"Enterprise Grade Security","icon":"Shield"}]'::jsonb,
  published BOOLEAN NOT NULL DEFAULT TRUE,
  meta_title TEXT NOT NULL DEFAULT '',
  meta_description TEXT NOT NULL DEFAULT '',
  target_keywords TEXT NOT NULL DEFAULT '',
  meta_robots TEXT NOT NULL DEFAULT 'index, follow',
  og_title TEXT NOT NULL DEFAULT '',
  og_description TEXT NOT NULL DEFAULT '',
  og_image TEXT NOT NULL DEFAULT '',
  og_url TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. Dynamic Custom SEO Pages (Automatically added to /sitemap.xml & routable at /:slug)
CREATE TABLE IF NOT EXISTS public.custom_pages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  subtitle TEXT NOT NULL DEFAULT '',
  badge TEXT NOT NULL DEFAULT 'AarviCloud Solutions',
  hero_image TEXT NOT NULL DEFAULT '',
  content_sections JSONB NOT NULL DEFAULT '[]'::jsonb,
  cta_title TEXT NOT NULL DEFAULT 'Ready to Accelerate Your Digital Roadmap?',
  cta_text TEXT NOT NULL DEFAULT 'Talk to our senior architects for a tailored consultation.',
  cta_btn_text TEXT NOT NULL DEFAULT 'Schedule Free Consultation',
  cta_btn_link TEXT NOT NULL DEFAULT '/contact',
  show_in_navbar BOOLEAN NOT NULL DEFAULT FALSE,
  show_in_footer BOOLEAN NOT NULL DEFAULT TRUE,
  published BOOLEAN NOT NULL DEFAULT TRUE,
  meta_title TEXT NOT NULL DEFAULT '',
  meta_description TEXT NOT NULL DEFAULT '',
  target_keywords TEXT NOT NULL DEFAULT '',
  meta_robots TEXT NOT NULL DEFAULT 'index, follow',
  og_title TEXT NOT NULL DEFAULT '',
  og_description TEXT NOT NULL DEFAULT '',
  og_image TEXT NOT NULL DEFAULT '',
  og_url TEXT NOT NULL DEFAULT '',
  priority NUMERIC(2,1) NOT NULL DEFAULT 0.8,
  changefreq TEXT NOT NULL DEFAULT 'weekly',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. Contact Form Submissions
CREATE TABLE IF NOT EXISTS public.contact_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT DEFAULT '',
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'new', -- 'new', 'read', 'replied'
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Enable Row Level Security (All access goes securely through backend service_role secret key)
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.page_seo ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.page_sections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.blogs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.portfolio_projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.case_studies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.custom_pages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_submissions ENABLE ROW LEVEL SECURITY;

-- Public read policies (optional, since our Express server proxies all requests with secret key)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read site_settings') THEN
    CREATE POLICY "Public read site_settings" ON public.site_settings FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read page_seo') THEN
    CREATE POLICY "Public read page_seo" ON public.page_seo FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read page_sections') THEN
    CREATE POLICY "Public read page_sections" ON public.page_sections FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read blogs') THEN
    CREATE POLICY "Public read blogs" ON public.blogs FOR SELECT USING (published = true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read portfolio_projects') THEN
    CREATE POLICY "Public read portfolio_projects" ON public.portfolio_projects FOR SELECT USING (published = true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read case_studies') THEN
    CREATE POLICY "Public read case_studies" ON public.case_studies FOR SELECT USING (published = true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read custom_pages') THEN
    CREATE POLICY "Public read custom_pages" ON public.custom_pages FOR SELECT USING (published = true);
  END IF;
END $$;
